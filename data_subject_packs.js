// Materia nueva (Administración › Materias): paquete genérico con su nombre (data_generic_subject.js)
function getSubjectPack(subjectId) {
    if (subjectPacks[subjectId]) return subjectPacks[subjectId];
    const { subjects } = require('./data_levels');
    const custom = subjects.find(s => s.id === subjectId && s.custom);
    return custom ? require('./data_generic_subject').genericPack(custom.name) : subjectPacks.tecnologia;
}

